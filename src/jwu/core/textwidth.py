SPACE = REGULAR[" "]
HAIR_W = REGULAR[HAIR]


def width(text: str, *, bold: bool = False) -> float:
    table = BOLD if bold else REGULAR
    total = 0.0
    for ch in text:
        if ch in table:
            total += table[ch]
        elif ch == "\ufe0f" or unicodedata.category(ch) in ("Mn", "Cf"):
            continue
        elif unicodedata.east_asian_width(ch) in ("W", "F") or ord(ch) > 0x2000:
            total += EMOJI
        else:
            total += 0.6
    return total


def pad(em: float) -> str:
    """Пробелы на заданную ширину: обычные + волосяные для остатка."""
    if em <= 0:
        return " "
    n = int(em // SPACE)
    return " " * n + HAIR * round((em - n * SPACE) / HAIR_W)


def _wrap(value: str, cap: float) -> list[str]:
    """Значение кусками не шире cap: сначала по стрелке «было → стало», потом по словам."""
    parts = value.split(" → ")
    pieces = [p + " →" for p in parts[:-1]] + [parts[-1]]
    out: list[str] = []
    for piece in pieces:
        line = ""
        for word in piece.split(" "):
            candidate = f"{line} {word}" if line else word
            if line and width(candidate) > cap:
                out.append(line)
                line = word
            else:
                line = candidate
        out.append(line)
    return out


def row(emoji: str, label: str, value: str, *, cap: float = CAP_TEXT) -> str:
    """HTML-строка «emoji **подпись** ……… значение», значение у правого края cap.

    Не влезает — значение строками ниже, тоже к правому краю. Пустое значение — только подпись.
    """
    head = (f"{emoji} " if emoji else "") + f"<b>{html.escape(label)}</b>"
    if not value:
        return head
    left = width(f"{emoji} " if emoji else "") + width(label, bold=True)
    gap = cap - left - width(value)
    if gap >= SPACE * 1.5:
        return head + pad(gap) + html.escape(value)
    lines = [head]
    for chunk in _wrap(value, cap):
        lines.append(pad(cap - width(chunk)) + html.escape(chunk))
    return "\n".join(lines)
